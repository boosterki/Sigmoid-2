    cost = cfg["fleet"]["cost"]
    c = st["concentration"]
    rec = fl["recommended"]
    t0, f0 = rec["trip_median"], rec["friction"]
    G = lambda a, fr, t=t0: float(grid[(grid.service_level.round(3) == a) & (grid.friction.round(2) == fr) & (grid.trip_median == t)].required_fleet.iloc[0])  # noqa: E731
    fv = flow[flow.trip_median == t0].iloc[0]
    wd = util[util.calendar_class == "workday"]
    hours_hi = int((wd.utilisation >= 0.5).sum())
    # ---- which explanations does the evidence support?
    B = c["top10pct_hours_share_mean"] >= 0.25 and rec["idle_share"] >= 0.5
    A = hours_hi >= 8 and rec["idle_share"] < 0.4
    D = h["decision"].startswith("reject")
